// Core document model for a Quanta Studio project.

export type TableKind = 'xy' | 'column' | 'grouped' | 'contingency' | 'survival' | 'parts' | 'multi';
export type YFormat = 'replicates' | 'meanSD' | 'meanSEM' | 'meanSDN' | 'meanSEMN';
export type Cell = number | null;

export interface DataSet {
  id: string;
  title: string;
  /** cols[subcolumn][row] */
  cols: Cell[][];
}

export interface DataTable {
  id: string;
  type: 'table';
  name: string;
  kind: TableKind;
  xTitle: string;
  x: Cell[];
  rowTitles: string[];
  yFormat: YFormat;
  replicates: number;
  datasets: DataSet[];
  /** keys of excluded cells: `${datasetId}:${sub}:${row}` */
  excluded: string[];
  notes: string;
  /** Set on tables generated by analyses (read-only). */
  derivedFrom?: string;
}

export type AnalysisKind =
  | 'descriptive'
  | 'normality'
  | 'oneSampleT'
  | 'ttest'
  | 'anova1'
  | 'anova2'
  | 'multipleT'
  | 'linreg'
  | 'correlation'
  | 'corrMatrix'
  | 'nonlin'
  | 'auc'
  | 'survival'
  | 'contingency'
  | 'fraction'
  | 'freqDist'
  | 'outliers'
  | 'roc'
  | 'blandAltman'
  | 'multiReg'
  | 'pca'
  | 'transform'
  | 'normalize'
  | 'rowStats';

export interface Analysis {
  id: string;
  type: 'analysis';
  name: string;
  kind: AnalysisKind;
  tableId: string;
  /** Data set ids to analyze. Empty/undefined = all. */
  datasetIds?: string[];
  params: Record<string, any>;
}

export type ChartType =
  | 'scatter'
  | 'bar'
  | 'box'
  | 'violin'
  | 'meanError'
  | 'beforeAfter'
  | 'xy'
  | 'groupedBar'
  | 'stackedBar'
  | 'groupedScatter'
  | 'survival'
  | 'pie'
  | 'donut'
  | 'histogram'
  | 'heatmap';

export type ErrorKind = 'sd' | 'sem' | 'ci95' | 'range' | 'iqr' | 'none';
export type MarkerShape = 'circle' | 'square' | 'triangle' | 'diamond' | 'cross' | 'plus' | 'triangleDown' | 'star' | 'none';

export interface AxisOptions {
  title: string;
  auto: boolean;
  min?: number;
  max?: number;
  scale: 'linear' | 'log10' | 'log2';
  tickInterval?: number;
  format?: 'auto' | 'decimal' | 'scientific' | 'power10' | 'percent';
  gridlines: boolean;
}

export interface SeriesStyle {
  color?: string;
  fill?: string;
  marker?: MarkerShape;
  markerSize?: number;
  lineWidth?: number;
  dash?: 'solid' | 'dash' | 'dot' | 'dashdot';
  label?: string;
  hidden?: boolean;
}

export interface Annotation {
  id: string;
  kind: 'bracket' | 'text' | 'line';
  /** Category indices (for column graphs) or x positions */
  from?: number;
  to?: number;
  y?: number;
  x?: number;
  text: string;
}

export interface GraphOptions {
  title: string;
  width: number;
  height: number;
  palette: string;
  errorBar: ErrorKind;
  errorDirection: 'both' | 'above' | 'below';
  center: 'mean' | 'median';
  showPoints: boolean;
  connectLines: boolean;
  pointSize: number;
  barWidth: number;
  lineWidth: number;
  fontFamily: string;
  fontSize: number;
  legend: 'auto' | 'right' | 'top' | 'none' | 'inside';
  xAxis: AxisOptions;
  yAxis: AxisOptions;
  series: Record<string, SeriesStyle>;
  whiskers: 'tukey' | 'minmax' | '5-95' | '10-90';
  survivalPercent: boolean;
  showCensored: boolean;
  showCI: boolean;
  theme: 'prism' | 'matlab' | 'minimal' | 'dark';
  frame: 'open' | 'box';
  barFill: 'solid' | 'hollow' | 'light';
  rotateXLabels: boolean;
  showFitCurves: boolean;
}

export interface Graph {
  id: string;
  type: 'graph';
  name: string;
  /** Table or analysis (for derived tables / survival) providing the data */
  tableId: string;
  analysisId?: string;
  chart: ChartType;
  datasetIds?: string[];
  options: GraphOptions;
  /** Nonlinear/linear regression analyses whose curves are overlaid. */
  fitAnalysisIds: string[];
  annotations: Annotation[];
}

export interface Script {
  id: string;
  type: 'script';
  name: string;
  code: string;
  path?: string;
}

export interface Figure {
  id: string;
  type: 'figure';
  name: string;
  number: number;
  spec: import('../graph/spec').FigureSpec;
}

export interface InfoSheet {
  id: string;
  type: 'info';
  name: string;
  text: string;
}

export interface Project {
  format: 'quanta-project';
  version: number;
  name: string;
  tables: DataTable[];
  analyses: Analysis[];
  graphs: Graph[];
  scripts: Script[];
  figures: Figure[];
  infos: InfoSheet[];
  created: string;
  modified: string;
}

export type ItemType = 'table' | 'analysis' | 'graph' | 'script' | 'figure' | 'info';
export type AnyItem = DataTable | Analysis | Graph | Script | Figure | InfoSheet;

export interface ResultTable {
  title: string;
  header: string[];
  rows: string[][];
  note?: string;
}

export interface FitCurve {
  datasetId: string;
  label: string;
  x: number[];
  y: number[];
  lo?: number[];
  hi?: number[];
}

export interface ComparisonMark {
  i: number;
  j: number;
  p: number;
  summary: string;
  row?: number;
}

export interface AnalysisOutput {
  tables: ResultTable[];
  warnings: string[];
  curves?: FitCurve[];
  derivedTable?: DataTable;
  comparisons?: ComparisonMark[];
  summary: string;
}
